-- Repairs databases created before reviews.id had an identity generator.
DO $$
DECLARE
    reviews_id_sequence TEXT;
BEGIN
    IF pg_get_serial_sequence('reviews', 'id') IS NULL THEN
        ALTER TABLE reviews
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    SELECT pg_get_serial_sequence('reviews', 'id')
    INTO reviews_id_sequence;

    PERFORM setval(
        reviews_id_sequence,
        COALESCE((SELECT MAX(id) FROM reviews), 0) + 1,
        FALSE
    );
END $$;